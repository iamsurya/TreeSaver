export function findVerifiedCompany(query: string): VerifiedCompany | undefined {
  const q = query.toLowerCase().trim();
  if (!q) return undefined;

  return VERIFIED_COMPANIES.find(c => {
    if (c.name.toLowerCase().includes(q) || q.includes(c.name.toLowerCase())) return true;
    if (c.domain.toLowerCase().includes(q) || q.includes(c.domain.toLowerCase())) return true;
    return c.aliases.some(a => a.toLowerCase().includes(q) || q.includes(a.toLowerCase()));
  });
}
